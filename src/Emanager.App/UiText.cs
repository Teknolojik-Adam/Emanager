        English.GroupBy(pair => pair.Value, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.First().Key, StringComparer.Ordinal);

    public static string Language { get; private set; } = "tr";
    public static void Use(string? language) => Language = language == "en" ? "en" : "tr";
    public static string T(string text) =>
        Language == "en" && English.TryGetValue(text, out var value) ? value : text;
    public static string Canonical(string text) =>
        Turkish.TryGetValue(text, out var original) ? original : text;
    public static string F(string template, params object?[] args) =>
        string.Format(CultureInfo.CurrentCulture, T(template), args);

